def _play_cached_track(track_name: str, mood: str) -> None:
    global _CURRENT_TRACK, _DESIRED_TRACK
    bgm = _BGM_CACHE.get(track_name)
    if bgm is None or _BGM_CHANNEL is None or not _MUSIC_ENABLED or not _READY:
        return
    pool = _MOOD_PLAYLISTS.get(mood, [track_name])
    # Single-track moods loop continuously; multi-track moods play 1 full ~30-45s pass then shuffle
    loops = -1 if len(pool) == 1 else 0
    _CURRENT_TRACK = track_name
    _DESIRED_TRACK = None
    try:
        _BGM_CHANNEL.stop()
        _BGM_CHANNEL.play(bgm, loops=loops, fade_ms=320)
    except pygame.error:
        pass


def _start_random_track(mood: str) -> None:
    """Picks a different random song from the mood pool, building asynchronously if needed."""
    global _DESIRED_TRACK
    pool = _MOOD_PLAYLISTS.get(mood)
    if not pool or not _MUSIC_ENABLED or not _READY or _BGM_CHANNEL is None:
        return

    choices = [t for t in pool if t != _CURRENT_TRACK] or pool
    pick = random.choice(choices)

    if pick in _BGM_CACHE:
        _play_cached_track(pick, mood)
        return

    with _BUILD_LOCK:
        raw = _READY_BYTES.pop(pick, None)
    if raw is not None:
        try:
            _BGM_CACHE[pick] = pygame.mixer.Sound(buffer=raw)
            _play_cached_track(pick, mood)
            return
        except pygame.error:
            return

    # Fade out current song smoothly while the new track synthesizes in the background
    _DESIRED_TRACK = pick
    try:
        if _BGM_CHANNEL.get_busy():
            _BGM_CHANNEL.fadeout(200)
    except pygame.error:
        pass

    with _BUILD_LOCK:
        if pick not in _BUILDING:
            _BUILDING.add(pick)
            threading.Thread(target=_bg_worker, args=(pick,), daemon=True).start()


def init(sfx_enabled: bool = True, music_enabled: bool = True) -> bool:
    global _SFX_ENABLED, _MUSIC_ENABLED, _READY, _SOUNDS, _BGM_CACHE, _BGM_CHANNEL
    _SFX_ENABLED = bool(sfx_enabled)
    _MUSIC_ENABLED = bool(music_enabled)
    try:
        current = pygame.mixer.get_init()
        if current != (SAMPLE_RATE, -16, 1):
            if current is not None:
                pygame.mixer.quit()
            pygame.mixer.init(frequency=SAMPLE_RATE, size=-16, channels=1, buffer=512)
        pygame.mixer.set_num_channels(8)
        pygame.mixer.set_reserved(1)
        _BGM_CHANNEL = pygame.mixer.Channel(0)
        _SOUNDS = _build_bank()
        _BGM_CACHE = {}
        _READY = True
    except pygame.error:
        _READY = False
        _SOUNDS = {}
        _BGM_CACHE = {}
        _BGM_CHANNEL = None
    return _READY


def set_sfx_enabled(enabled: bool) -> None:
    """Toggles sound effects without disturbing Channel 0 background music."""
    global _SFX_ENABLED
    _SFX_ENABLED = bool(enabled)
    if not _SFX_ENABLED and _READY:
        try:
            for ch_idx in range(1, pygame.mixer.get_num_channels()):
                pygame.mixer.Channel(ch_idx).stop()
        except pygame.error:
            pass


def set_music_enabled(enabled: bool) -> None:
    """Toggles background music without disturbing sound effects."""
    global _MUSIC_ENABLED, _DESIRED_TRACK
    _MUSIC_ENABLED = bool(enabled)
    if not _READY or _BGM_CHANNEL is None:
        return
    if not _MUSIC_ENABLED:
        _DESIRED_TRACK = None
        try:
            _BGM_CHANNEL.fadeout(180)
        except pygame.error:
            pass
    elif _CURRENT_MOOD and not _PAUSED_BGM:
        _start_random_track(_CURRENT_MOOD)


def is_sfx_enabled() -> bool:
    return _SFX_ENABLED


def is_music_enabled() -> bool:
    return _MUSIC_ENABLED


def set_enabled(enabled: bool) -> None:
    set_sfx_enabled(enabled)
    set_music_enabled(enabled)


def is_enabled() -> bool:
    return _SFX_ENABLED or _MUSIC_ENABLED


def play(name: str) -> None:
    if not _SFX_ENABLED or not _READY:
        return
    snd = _SOUNDS.get(name)
    if snd is not None:
        try:
            snd.play()
        except pygame.error:
            pass


def set_mood(mood: str, force: bool = False) -> None:
    """Switches mood playlist only if the mood actually changed (seamless across scenes)."""
    global _CURRENT_MOOD, _PAUSED_BGM
    mood = _LEGACY_MOOD_MAP.get(mood, mood)
    if mood not in _MOOD_PLAYLISTS:
        return

    _PAUSED_BGM = False
    active = _BGM_CHANNEL is not None and (_BGM_CHANNEL.get_busy() or _DESIRED_TRACK is not None)
    if not force and _CURRENT_MOOD == mood and active:
        return

    _CURRENT_MOOD = mood
    if _MUSIC_ENABLED:
        _start_random_track(mood)


def play_music(track_name: str, force: bool = False) -> None:
    """Routes scene track requests to mood playlists."""
    set_mood(track_name, force=force)


def update() -> None:
    """Picks up finished background builds and shuffles to a new song when a track ends."""
    if not _MUSIC_ENABLED or not _READY or _PAUSED_BGM or not _CURRENT_MOOD or _BGM_CHANNEL is None:
        return

    if _DESIRED_TRACK is not None:
        with _BUILD_LOCK:
            raw = _READY_BYTES.pop(_DESIRED_TRACK, None)
        if raw is not None:
            try:
                _BGM_CACHE[_DESIRED_TRACK] = pygame.mixer.Sound(buffer=raw)
                _play_cached_track(_DESIRED_TRACK, _CURRENT_MOOD)
            except pygame.error:
                pass
        return

    if not _BGM_CHANNEL.get_busy():
        _start_random_track(_CURRENT_MOOD)


def stop_music() -> None:
    """Fades out BGM and pauses auto-shuffle until the next set_mood() call."""
    global _PAUSED_BGM, _DESIRED_TRACK
    _PAUSED_BGM = True
    _DESIRED_TRACK = None
    if _READY and _BGM_CHANNEL is not None:
        try:
            _BGM_CHANNEL.fadeout(180)
        except pygame.error:
            pass