def is_night_time(config: dict | None = None) -> bool:
    """Returns True when sky_mode is Night or real local time is 8:00 PM - 5:00 AM."""
    sky_mode = (config or {}).get("sky_mode", "auto")
    if sky_mode == "night":
        return True
    if sky_mode in ("dawn", "day", "sunset"):
        return False
    hour = datetime.now().hour
    return hour >= 20 or hour < 5


def _note_hz(name: str) -> float:
    if not name or name in ("R", "-"):
        return 0.0
    semi = _SEMITONES[name[0].upper()]
    idx = 1
    if idx < len(name) and name[idx] in ("#", "b"):
        semi += 1 if name[idx] == "#" else -1
        idx += 1
    octave = int(name[idx:])
    midi = (octave + 1) * 12 + semi
    return 440.0 * (2.0 ** ((midi - 69) / 12.0))


def _gen_tone(
    freq: float,
    dur_ms: int,
    wave: str = "square",
    vol: float = 0.24,
    slide_to: float | None = None,
    decay: bool = True,
) -> array:
    n = max(1, int(SAMPLE_RATE * dur_ms / 1000))
    buf = array("h")
    phase = 0.0
    rng = random.Random(int(freq) + dur_ms)

    for i in range(n):
        t = i / n
        if freq <= 0:
            buf.append(0)
            continue

        cur_f = freq + (slide_to - freq) * t if slide_to is not None else freq
        phase += cur_f / SAMPLE_RATE
        frac = phase - math.floor(phase)

        if wave == "square":
            raw = 1.0 if frac < 0.5 else -1.0
        elif wave == "pulse25":
            raw = 1.0 if frac < 0.25 else -1.0
        elif wave == "triangle":
            raw = 4.0 * abs(frac - 0.5) - 1.0
        elif wave == "noise":
            raw = rng.uniform(-1.0, 1.0)
        else:
            raw = math.sin(2.0 * math.pi * phase)

        env = (1.0 - t * 0.85) if decay else 1.0
        if i < 40:
            env *= i / 40.0
        sample = int(max(-1.0, min(1.0, raw * vol * env)) * 32767)
        buf.append(sample)
    return buf


def _seq(steps: list[tuple]) -> pygame.mixer.Sound:
    out = array("h")
    for step in steps:
        freq = step[0]
        dur_ms = step[1]
        wave = step[2] if len(step) > 2 else "square"
        vol = step[3] if len(step) > 3 else 0.22
        slide_to = step[4] if len(step) > 4 else None
        out.extend(_gen_tone(freq, dur_ms, wave=wave, vol=vol, slide_to=slide_to))
    return pygame.mixer.Sound(buffer=out.tobytes())


def _build_drum_samples() -> dict[str, list[int]]:
    """Pre-generates compact retro drum hits at HALF_RATE for fast section mixing."""
    two_pi = 2.0 * math.pi
    rng = random.Random(77)

    # Kick: fast pitch drop 145Hz -> 42Hz
    kn = int(HALF_RATE * 0.070)
    kick: list[int] = []
    phase = 0.0
    for i in range(kn):
        t = i / kn
        f = 145.0 * (1.0 - t) + 42.0 * t
        phase += f / HALF_RATE
        env = (1.0 - t) ** 1.6
        kick.append(int(math.sin(two_pi * phase) * 0.075 * env * 32767))

    # Snare: crisp noise burst + 210Hz body
    sn = int(HALF_RATE * 0.060)
    snare: list[int] = []
    phase = 0.0
    for i in range(sn):
        t = i / sn
        phase += 210.0 / HALF_RATE
        env = (1.0 - t) ** 1.8
        raw = rng.uniform(-0.7, 0.7) + 0.3 * math.sin(two_pi * phase)
        snare.append(int(raw * 0.055 * env * 32767))

    # Hi-hat: crisp short noise tick
    hn = int(HALF_RATE * 0.022)
    hat = [int(rng.uniform(-1.0, 1.0) * 0.026 * (1.0 - i / hn) * 32767) for i in range(hn)]

    # Soft day tick: gentle percussive pulse for Day A' lift
    tn = int(HALF_RATE * 0.016)
    tick = [int(rng.uniform(-1.0, 1.0) * 0.016 * (1.0 - i / tn) * 32767) for i in range(tn)]

    return {"K": kick, "S": snare, "H": hat, "T": tick}


_DRUMS = _build_drum_samples()


def _add_voice_into(
    mix: list[int],
    notes: list[tuple[str, float]],
    beat_sec: float,
    wave: str,
    vol: float,
    decay: float,
) -> None:
    """Mixes one melodic voice directly into a fixed-length section buffer."""
    two_pi = 2.0 * math.pi
    sin_fn = math.sin
    mix_len = len(mix)
    beat_cursor = 0.0
    scale = vol * 32767.0

    for note_name, beats in notes:
        start_i = int(round(beat_cursor * beat_sec * HALF_RATE))
        beat_cursor += beats
        end_i = min(mix_len, int(round(beat_cursor * beat_sec * HALF_RATE)))
        n = end_i - start_i
        if n <= 0:
            continue

        freq = _note_hz(note_name)
        if freq <= 0.0:
            continue

        step = freq / HALF_RATE
        phase = 0.0
        fade_in = min(30, n // 4) or 1
        fade_out = min(40, n // 4) or 1
        inv_n = 1.0 / n

        for j in range(n):
            phase += step
            frac = phase - int(phase)
            if wave == "square":
                raw = 1.0 if frac < 0.5 else -1.0
            elif wave == "pulse25":
                raw = 1.0 if frac < 0.25 else -1.0
            elif wave == "triangle":
                raw = 4.0 * abs(frac - 0.5) - 1.0
            else:
                raw = sin_fn(two_pi * frac)

            env = 1.0 - (j * inv_n) * decay
            if j < fade_in:
                env *= j / fade_in
            elif j > n - fade_out:
                env *= (n - j) / fade_out
            mix[start_i + j] += int(raw * scale * env)


def _add_drums_into(mix: list[int], pattern: str, beat_sec: float) -> None:
    mix_len = len(mix)
    for idx, ch in enumerate(pattern):
        hit = _DRUMS.get(ch)
        if not hit:
            continue
        start_i = int(round(idx * 0.5 * beat_sec * HALF_RATE))
        limit = min(len(hit), mix_len - start_i)
        for j in range(limit):
            mix[start_i + j] += hit[j]


def _build_bgm_bytes(track_name: str) -> bytes | None:
    """Synthesizes a full multi-section song into 22050 Hz PCM bytes (thread-safe)."""
    spec = _SONG_DEFS.get(track_name)
    if spec is None:
        return None

    beat_sec = 60.0 / spec["bpm"]
    sec_samples = max(1, int(round(16.0 * beat_sec * HALF_RATE)))
    out = array("h")

    for lead_notes, bass_notes, arp_notes, drum_pat in spec["sections"]:
        mix = [0] * sec_samples
        _add_voice_into(mix, lead_notes, beat_sec, spec["lead_wave"], spec["lead_vol"], spec["decay"])
        _add_voice_into(
            mix, bass_notes, beat_sec, spec["bass_wave"], spec["bass_vol"], min(0.85, spec["decay"] + 0.1)
        )
        if arp_notes:
            _add_voice_into(mix, arp_notes, beat_sec, spec["arp_wave"], spec["arp_vol"], 0.65)
        if drum_pat:
            _add_drums_into(mix, drum_pat, beat_sec)

        for sample in mix:
            if sample > 32767:
                sample = 32767
            elif sample < -32767:
                sample = -32767
            # Upsample 2x to match the 22050 Hz mixer
            out.append(sample)
            out.append(sample)

    return out.tobytes()


def _bg_worker(track_name: str) -> None:
    raw = _build_bgm_bytes(track_name)
    with _BUILD_LOCK:
        _BUILDING.discard(track_name)
        if raw is not None:
            _READY_BYTES[track_name] = raw


