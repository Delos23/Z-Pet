def _try_open_mixer() -> tuple[tuple[int, int, int] | None, str]:
    """Prefers native 48 kHz mono (1ch) on Cardputer Zero with clean PipeWire/Pulse/ALSA fallback."""
    preset = os.environ.get("SDL_AUDIODRIVER")
    if preset == "dummy":
        os.environ.pop("SDL_AUDIODRIVER", None)
        preset = None

    if preset:
        drivers = [preset]
    elif os.name == "nt":
        drivers = [None]
    else:
        drivers = ["pipewire", "pulseaudio", "alsa", None]

    buf_size = 1024 if os.name == "nt" else 2048
    modes = (
        ((44100, 1), (48000, 1), (44100, 2))
        if os.name == "nt"
        else ((48000, 1), (44100, 1), (48000, 2), (44100, 2))
    )
    last_err = ""

    for drv in drivers:
        if drv is None:
            os.environ.pop("SDL_AUDIODRIVER", None)
        else:
            os.environ["SDL_AUDIODRIVER"] = drv
        for freq, ch in modes:
            try:
                if pygame.mixer.get_init() is not None:
                    pygame.mixer.quit()
                pygame.mixer.init(
                    frequency=freq,
                    size=-16,
                    channels=ch,
                    buffer=buf_size,
                    allowedchanges=0,
                )
                cfg = pygame.mixer.get_init()
                if cfg is not None and cfg[1] == -16:
                    return cfg, drv or "auto"
            except pygame.error as exc:
                last_err = str(exc)
    return None, last_err


def init(sfx_enabled: bool = True, music_enabled: bool = True) -> bool:
    global _SFX_ENABLED, _MUSIC_ENABLED, _READY, _SOUNDS, _BGM_CHANNEL
    global _MIXER_RATE, _MIXER_CH, _BGM_DIV, _BGM_RATE, _DRUMS, _WORKER_STARTED
    _SFX_ENABLED = bool(sfx_enabled)
    _MUSIC_ENABLED = bool(music_enabled)

    cfg, info = _try_open_mixer()
    if cfg is None:
        print(f"Z-Pet audio disabled: {info}")
        _READY = False
        _SOUNDS = {}
        _SECTION_CACHE.clear()
        _BGM_CHANNEL = None
        return False

    _MIXER_RATE, fmt, _MIXER_CH = cfg
    _BGM_DIV = 2 if _MIXER_RATE >= 32000 else 1
    _BGM_RATE = _MIXER_RATE / _BGM_DIV
    _DRUMS = _build_drum_samples(_BGM_RATE)

    pygame.mixer.set_num_channels(8)
    pygame.mixer.set_reserved(1)
    _BGM_CHANNEL = pygame.mixer.Channel(0)
    _SOUNDS = _build_bank()
    _SECTION_CACHE.clear()
    _READY = True

    if not _WORKER_STARTED:
        _WORKER_STARTED = True
        threading.Thread(target=_worker_loop, daemon=True).start()

    print(
        f"Z-Pet audio ready: {_MIXER_RATE}Hz fmt={fmt} {_MIXER_CH}ch "
        f"(driver={info}, sfx={_SFX_ENABLED}, music={_MUSIC_ENABLED})"
    )
    return True


def set_sfx_enabled(enabled: bool) -> None:
    global _SFX_ENABLED
    _SFX_ENABLED = bool(enabled)
    if not _SFX_ENABLED and _READY:
        try:
            for ch_idx in range(1, pygame.mixer.get_num_channels()):
                pygame.mixer.Channel(ch_idx).stop()
        except pygame.error:
            pass


def set_music_enabled(enabled: bool) -> None:
    global _MUSIC_ENABLED, _NEED_PLAY_SEC, _NEED_QUEUE_SEC, _QUEUED_SEC
    _MUSIC_ENABLED = bool(enabled)
    if not _READY or _BGM_CHANNEL is None:
        return
    if not _MUSIC_ENABLED:
        _NEED_PLAY_SEC = None
        _NEED_QUEUE_SEC = None
        _QUEUED_SEC = None
        try:
            _BGM_CHANNEL.stop()
        except pygame.error:
            pass
    elif _CURRENT_MOOD and not _PAUSED_BGM:
        _start_random_track(_CURRENT_MOOD)


