def is_night_time(config: dict | None = None) -> bool:
    """Returns True when sky_mode is Night or real local time is 8:00 PM - 5:00 AM."""
    sky_mode = (config or {}).get("sky_mode", "auto")
    if sky_mode == "night":
        return True
    if sky_mode in ("dawn", "day", "sunset"):
        return False
    hour = datetime.now().hour
    return hour >= 20 or hour < 5


def _note_hz(name: str) -> float:
    if not name or name in ("R", "-"):
        return 0.0
    semi = _SEMITONES[name[0].upper()]
    idx = 1
    if idx < len(name) and name[idx] in ("#", "b"):
        semi += 1 if name[idx] == "#" else -1
        idx += 1
    octave = int(name[idx:])
    midi = (octave + 1) * 12 + semi
    return 440.0 * (2.0 ** ((midi - 69) / 12.0))


def _gen_tone(
    freq: float,
    dur_ms: int,
    wave: str = "square",
    vol: float = 0.24,
    slide_to: float | None = None,
    decay: bool = True,
) -> array:
    """Synthesizes a clean band-limited 16-bit tone matching mixer rate and channels."""
    rate = _MIXER_RATE
    ch = _MIXER_CH
    n = max(1, int(rate * dur_ms / 1000))
    buf = array("h")
    phase = 0.0
    rng = random.Random(int(freq) + dur_ms)
    tbl = _WAVETABLES.get(wave, _WAVETABLES["sine"])
    wt_over_rate = _WT_SIZE / rate
    mask = _WT_MASK
    is_noise = wave == "noise"
    filt = 0.0
    attack = max(1, int(rate * 0.003))
    release = max(1, int(rate * 0.004))

    for i in range(n):
        t = i / n
        if freq <= 0:
            buf.append(0)
            if ch == 2:
                buf.append(0)
            continue

        cur_f = freq + (slide_to - freq) * t if slide_to is not None else freq
        if is_noise:
            raw = rng.uniform(-1.0, 1.0)
            filt += 0.45 * (raw - filt)
            raw = filt
        else:
            phase += cur_f * wt_over_rate
            raw = tbl[int(phase) & mask]

        env = (1.0 - t * 0.85) if decay else 1.0
        if i < attack:
            env *= i / attack
        elif i > n - release:
            env *= (n - i) / release
        sample = int(max(-1.0, min(1.0, raw * vol * env)) * 28000)
        buf.append(sample)
        if ch == 2:
            buf.append(sample)
    return buf


def _seq(steps: list[tuple]) -> pygame.mixer.Sound:
    out = array("h")
    for step in steps:
        freq = step[0]
        dur_ms = step[1]
        wave = step[2] if len(step) > 2 else "square"
        vol = step[3] if len(step) > 3 else 0.24
        slide_to = step[4] if len(step) > 4 else None
        out.extend(_gen_tone(freq, dur_ms, wave=wave, vol=vol, slide_to=slide_to))
    return pygame.mixer.Sound(buffer=out.tobytes())


def _build_drum_samples(bgm_rate: float) -> dict[str, list[int]]:
    two_pi = 2.0 * math.pi
    rng = random.Random(77)

    kn = max(1, int(bgm_rate * 0.055))
    kick: list[int] = []
    phase = 0.0
    for i in range(kn):
        t = i / kn
        f = 190.0 * (1.0 - t) + 110.0 * t
        phase += f / bgm_rate
        env = (1.0 - t) ** 1.7
        kick.append(int(math.sin(two_pi * phase) * 0.14 * env * 28000))

    sn = max(1, int(bgm_rate * 0.052))
    snare: list[int] = []
    phase = 0.0
    filt = 0.0
    for i in range(sn):
        t = i / sn
        phase += 250.0 / bgm_rate
        env = (1.0 - t) ** 1.8
        raw = rng.uniform(-0.65, 0.65) + 0.35 * math.sin(two_pi * phase)
        filt += 0.55 * (raw - filt)
        snare.append(int(filt * 0.11 * env * 28000))

    hn = max(1, int(bgm_rate * 0.020))
    hat = [int(rng.uniform(-1.0, 1.0) * 0.055 * (1.0 - i / hn) * 28000) for i in range(hn)]

    tn = max(1, int(bgm_rate * 0.015))
    tick = [int(rng.uniform(-1.0, 1.0) * 0.035 * (1.0 - i / tn) * 28000) for i in range(tn)]

    return {"K": kick, "S": snare, "H": hat, "T": tick}


def _add_voice_into(
    mix: list[int],
    notes: list[tuple[str, float]],
    beat_sec: float,
    wave: str,
    vol: float,
    decay: float,
    bgm_rate: float,
    min_hz: float = 0.0,
) -> None:
    """Fast wavetable voice mixer with zero aliasing."""
    tbl = _WAVETABLES.get(wave, _WAVETABLES["sine"])
    mix_len = len(mix)
    beat_cursor = 0.0
    scale = vol * 28000.0
    wt_over_rate = _WT_SIZE / bgm_rate
    mask = _WT_MASK

    for note_name, beats in notes:
        start_i = int(round(beat_cursor * beat_sec * bgm_rate))
        beat_cursor += beats
        end_i = min(mix_len, int(round(beat_cursor * beat_sec * bgm_rate)))
        n = end_i - start_i
        if n <= 0:
            continue

        freq = _note_hz(note_name)
        if freq <= 0.0:
            continue
        if min_hz > 0.0:
            while freq < min_hz:
                freq *= 2.0

        step = freq * wt_over_rate
        phase = 0.0
        fade_in = min(40, n // 4) or 1
        fade_out = min(60, n // 4) or 1
        inv_n = 1.0 / n

        for j in range(n):
            phase += step
            raw = tbl[int(phase) & mask]
            env = 1.0 - (j * inv_n) * decay
            if j < fade_in:
                env *= j / fade_in
            elif j > n - fade_out:
                env *= (n - j) / fade_out
            mix[start_i + j] += int(raw * scale * env)


def _add_drums_into(mix: list[int], pattern: str, beat_sec: float, bgm_rate: float) -> None:
    mix_len = len(mix)
    for idx, ch in enumerate(pattern):
        hit = _DRUMS.get(ch)
        if not hit:
            continue
        start_i = int(round(idx * 0.5 * beat_sec * bgm_rate))
        limit = min(len(hit), mix_len - start_i)
        for j in range(limit):
            mix[start_i + j] += hit[j]


def _build_section_bytes(track_name: str, sec_idx: int) -> bytes | None:
    """Synthesizes one 16-beat section with smooth 2x linear interpolation."""
    spec = _SONG_DEFS.get(track_name)
    if spec is None or sec_idx < 0 or sec_idx >= len(spec["sections"]):
        return None

    bgm_rate = _BGM_RATE
    beat_sec = 60.0 / spec["bpm"]
    sec_samples = max(1, int(round(16.0 * beat_sec * bgm_rate)))
    lead_notes, bass_notes, arp_notes, drum_pat = spec["sections"][sec_idx]

    mix = [0] * sec_samples
    _add_voice_into(mix, lead_notes, beat_sec, spec["lead_wave"], spec["lead_vol"], spec["decay"], bgm_rate)
    _add_voice_into(
        mix,
        bass_notes,
        beat_sec,
        "triangle",
        spec["bass_vol"],
        min(0.85, spec["decay"] + 0.1),
        bgm_rate,
        min_hz=130.0,
    )
    if arp_notes:
        _add_voice_into(mix, arp_notes, beat_sec, spec["arp_wave"], spec["arp_vol"], 0.65, bgm_rate)
    if drum_pat:
        _add_drums_into(mix, drum_pat, beat_sec, bgm_rate)

    out = array("h")
    ch = _MIXER_CH
    if _BGM_DIV == 2:
        prev = 0
        if ch == 1:
            for s in mix:
                if s > 28000:
                    s = 28000
                elif s < -28000:
                    s = -28000
                out.append((prev + s) >> 1)
                out.append(s)
                prev = s
        else:
            for s in mix:
                if s > 28000:
                    s = 28000
                elif s < -28000:
                    s = -28000
                mid = (prev + s) >> 1
                out.append(mid)
                out.append(mid)
                out.append(s)
                out.append(s)
                prev = s
    else:
        if ch == 1:
            for s in mix:
                if s > 28000:
                    s = 28000
                elif s < -28000:
                    s = -28000
                out.append(s)
        else:
            for s in mix:
                if s > 28000:
                    s = 28000
                elif s < -28000:
                    s = -28000
                out.append(s)
                out.append(s)

    return out.tobytes()


def _worker_loop() -> None:
    while True:
        _BUILD_EVENT.wait()
        while True:
            with _BUILD_LOCK:
                if not _BUILD_QUEUE:
                    _BUILD_EVENT.clear()
                    break
                key = _BUILD_QUEUE.popleft()
            try:
                raw = _build_section_bytes(key[0], key[1])
            except Exception as exc:
                print(f"Z-Pet BGM build error {key}: {exc}")
                raw = None
            with _BUILD_LOCK:
                _QUEUED_FOR_BUILD.discard(key)
                if raw is not None:
                    _READY_SEC_BYTES[key] = raw
            time.sleep(0.002)


def _request_section(track_name: str, sec_idx: int, urgent: bool = False) -> None:
    key = (track_name, sec_idx)
    if key in _SECTION_CACHE:
        return
    with _BUILD_LOCK:
        if key in _READY_SEC_BYTES:
            return
        if key in _QUEUED_FOR_BUILD:
            if urgent and key in _BUILD_QUEUE:
                _BUILD_QUEUE.remove(key)
                _BUILD_QUEUE.appendleft(key)
            return
        _QUEUED_FOR_BUILD.add(key)
        if urgent:
            _BUILD_QUEUE.appendleft(key)
        else:
            _BUILD_QUEUE.append(key)
        _BUILD_EVENT.set()


def _harvest_ready() -> None:
    with _BUILD_LOCK:
        if not _READY_SEC_BYTES:
            return
        ready = dict(_READY_SEC_BYTES)
        _READY_SEC_BYTES.clear()
    for key, raw in ready.items():
        if key not in _SECTION_CACHE:
            try:
                _SECTION_CACHE[key] = pygame.mixer.Sound(buffer=raw)
            except pygame.error as exc:
                print(f"Z-Pet BGM load error {key}: {exc}")


def _pick_next_track(mood: str, avoid: str | None) -> str | None:
    pool = _MOOD_PLAYLISTS.get(mood)
    if not pool:
        return None
    choices = [t for t in pool if t != avoid] or pool
    return random.choice(choices)


def _schedule_next_section() -> None:
    global _NEED_QUEUE_SEC, _NEXT_RANDOM_TRACK
    if not _PLAYING_TRACK or not _CURRENT_MOOD:
        return
    spec = _SONG_DEFS.get(_PLAYING_TRACK)
    if spec is None:
        return
    num_secs = len(spec["sections"])
    next_idx = _PLAYING_SEC + 1

    if next_idx < num_secs:
        _NEED_QUEUE_SEC = (_PLAYING_TRACK, next_idx)
        _request_section(_PLAYING_TRACK, next_idx, urgent=False)
        return

    pool = _MOOD_PLAYLISTS.get(_CURRENT_MOOD, [_PLAYING_TRACK])
    if len(pool) == 1:
        _NEED_QUEUE_SEC = (_PLAYING_TRACK, 0)
        _request_section(_PLAYING_TRACK, 0, urgent=False)
    else:
        _NEED_QUEUE_SEC = None
        _NEXT_RANDOM_TRACK = _pick_next_track(_CURRENT_MOOD, _PLAYING_TRACK)
        if _NEXT_RANDOM_TRACK:
            _request_section(_NEXT_RANDOM_TRACK, 0, urgent=False)


def _play_section_now(track_name: str, sec_idx: int) -> None:
    global _PLAYING_TRACK, _PLAYING_SEC, _QUEUED_SEC, _NEED_PLAY_SEC, _NEED_QUEUE_SEC
    snd = _SECTION_CACHE.get((track_name, sec_idx))
    if snd is None or _BGM_CHANNEL is None or not _MUSIC_ENABLED or not _READY:
        return
    _PLAYING_TRACK = track_name
    _PLAYING_SEC = sec_idx
    _QUEUED_SEC = None
    _NEED_PLAY_SEC = None
    _NEED_QUEUE_SEC = None
    try:
        _BGM_CHANNEL.stop()
        _BGM_CHANNEL.play(snd, loops=0)
        if sec_idx == 0:
            print(f"Z-Pet BGM playing: {track_name}")
    except pygame.error as exc:
        print(f"Z-Pet BGM play error: {exc}")
        return
    _schedule_next_section()


def _start_random_track(mood: str) -> None:
    global _PLAYING_TRACK, _PLAYING_SEC, _QUEUED_SEC, _NEED_PLAY_SEC, _NEED_QUEUE_SEC, _NEXT_RANDOM_TRACK
    if not _MUSIC_ENABLED or not _READY or _BGM_CHANNEL is None:
        return

    pool = _MOOD_PLAYLISTS.get(mood)
    if not pool:
        return

    if _NEXT_RANDOM_TRACK and _NEXT_RANDOM_TRACK in pool and _NEXT_RANDOM_TRACK != _PLAYING_TRACK:
        pick = _NEXT_RANDOM_TRACK
    else:
        pick = _pick_next_track(mood, _PLAYING_TRACK)
    _NEXT_RANDOM_TRACK = None
    if not pick:
        return

    _harvest_ready()
    if (pick, 0) in _SECTION_CACHE:
        _play_section_now(pick, 0)
        return

    # On initial startup (empty cache), build section 0 immediately so music begins at once
    if not _SECTION_CACHE:
        raw = _build_section_bytes(pick, 0)
        if raw is not None:
            try:
                _SECTION_CACHE[(pick, 0)] = pygame.mixer.Sound(buffer=raw)
                _play_section_now(pick, 0)
                return
            except pygame.error as exc:
                print(f"Z-Pet BGM startup error: {exc}")

    _PLAYING_TRACK = pick
    _PLAYING_SEC = -1
    _QUEUED_SEC = None
    _NEED_QUEUE_SEC = None
    _NEED_PLAY_SEC = (pick, 0)
    try:
        _BGM_CHANNEL.stop()
    except pygame.error:
        pass
    _request_section(pick, 0, urgent=True)


